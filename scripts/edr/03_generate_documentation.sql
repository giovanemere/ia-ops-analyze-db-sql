-- Generar Documentación Automática de la BD
USE [persqldbmotorpromocprd];

-- Crear vista con información completa de tablas
CREATE OR ALTER VIEW vw_TableDocumentation AS
SELECT 
    t.TABLE_SCHEMA as Esquema,
    t.TABLE_NAME as Tabla,
    c.COLUMN_NAME as Columna,
    c.DATA_TYPE as Tipo_Dato,
    ISNULL(CAST(c.CHARACTER_MAXIMUM_LENGTH AS VARCHAR), '') as Longitud,
    c.IS_NULLABLE as Permite_NULL,
    ISNULL(c.COLUMN_DEFAULT, '') as Valor_Default,
    CASE WHEN pk.COLUMN_NAME IS NOT NULL THEN 'Sí' ELSE 'No' END as Es_Primary_Key,
    CASE WHEN fk.COLUMN_NAME IS NOT NULL THEN 'Sí' ELSE 'No' END as Es_Foreign_Key,
    ISNULL(fk.REFERENCED_TABLE_NAME, '') as Tabla_Referenciada
FROM INFORMATION_SCHEMA.TABLES t
INNER JOIN INFORMATION_SCHEMA.COLUMNS c ON t.TABLE_NAME = c.TABLE_NAME
LEFT JOIN (
    SELECT ku.TABLE_NAME, ku.COLUMN_NAME
    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
    INNER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE ku ON tc.CONSTRAINT_NAME = ku.CONSTRAINT_NAME
    WHERE tc.CONSTRAINT_TYPE = 'PRIMARY KEY'
) pk ON c.TABLE_NAME = pk.TABLE_NAME AND c.COLUMN_NAME = pk.COLUMN_NAME
LEFT JOIN (
    SELECT 
        ku.TABLE_NAME, 
        ku.COLUMN_NAME,
        rc.UNIQUE_CONSTRAINT_NAME,
        rt.TABLE_NAME as REFERENCED_TABLE_NAME
    FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
    INNER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE ku ON rc.CONSTRAINT_NAME = ku.CONSTRAINT_NAME
    INNER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE rt ON rc.UNIQUE_CONSTRAINT_NAME = rt.CONSTRAINT_NAME
) fk ON c.TABLE_NAME = fk.TABLE_NAME AND c.COLUMN_NAME = fk.COLUMN_NAME
WHERE t.TABLE_TYPE = 'BASE TABLE';

-- Consultar la documentación
SELECT * FROM vw_TableDocumentation ORDER BY Esquema, Tabla, Columna;
